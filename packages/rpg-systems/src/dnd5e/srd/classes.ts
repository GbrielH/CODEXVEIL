/** Valor da tabela para o nível (1 a 20). */
export function atLevel(table: LevelTable, level: number): number {
  return table[Math.min(Math.max(Math.trunc(level), 1), 20) - 1] ?? 0;
}

/** Tabela com mudanças a partir de certos níveis: `{ 1: 2, 3: 3 }` = 2 do 1º ao 2º, 3 do 3º em diante. */
function steps(changes: Record<number, number>): LevelTable {
  const result: number[] = [];
  let current = 0;
  for (let level = 1; level <= 20; level++) {
    const change = changes[level];
    if (change !== undefined) current = change;
    result.push(current);
  }
  return result;
}

