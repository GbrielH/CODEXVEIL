-- Grade (2026-10-21): imagem própria nos tokens. O token mostra, nesta ordem, a imagem
-- enviada pelo mestre, a foto do personagem ou a imagem da criatura; sem nenhuma, as iniciais.
-- A imagem fica em campaigns/{id}/maps/ e o jogador só lê a de token visível do mapa ativo.
-- As paredes ganham estilo no 5º item de cada parede ([x1, y1, x2, y2, "estilo"]), sem mudança
-- de esquema (a coluna `walls` já é JSON).

alter table public.map_tokens
  add column image_path text check (image_path is null or char_length(image_path) <= 300);

grant update (image_path) on table public.map_tokens to authenticated;

create or replace function private.can_read_campaign_media(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_parts text[] := string_to_array(p_name, '/');
  v_id uuid := private.try_uuid(v_parts[2]);
begin
  if v_id is null then
    return false;
  end if;

  if v_parts[1] = 'characters' then
    return private.can_view_character(v_id);
  elsif v_parts[1] = 'campaigns' then
    if private.is_campaign_gm(v_id) then
      return true;
    end if;
    if not private.is_campaign_member(v_id) then
      return false;
    end if;
    case v_parts[3]
      when 'cover' then
        return true;
      when 'creatures' then
        return exists (
          select 1 from public.creatures c
          where c.campaign_id = v_id and c.image_path = p_name and c.visibility = 'members'
        );
      when 'sessions' then
        return exists (
          select 1
          from public.session_blocks b
          join public.sessions s on s.id = b.session_id
          where b.campaign_id = v_id
            and b.type = 'image'
            and b.visibility = 'members'
            and s.is_published
            and b.data ->> 'path' = p_name
        );
      when 'maps' then
        return exists (
          select 1 from public.session_maps m
          where m.campaign_id = v_id and m.is_active and m.image_path = p_name
        ) or exists (
          select 1 from public.map_tokens t
          join public.session_maps m on m.id = t.map_id
          where t.campaign_id = v_id and m.is_active and not t.is_hidden and t.image_path = p_name
        );
      else
        return false;
    end case;
  end if;
  return false;
end;
$$;
